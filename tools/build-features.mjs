/* Generate assets/js/features.js from web/mockup/data/features.json (single source of data) */
import { readFileSync, writeFileSync } from "node:fs";
const src = JSON.parse(readFileSync("web/mockup/data/features.json", "utf8"));
const out = `/* AUTO-GENERATED by tools/build-features.mjs - do not edit manually */
window.FPANEL_CATEGORIES = ${JSON.stringify(src.categories, null, 2)};
window.FPANEL_FEATURES = ${JSON.stringify(src.features, null, 2)};
`;
writeFileSync("web/mockup/assets/js/features.js", out);
console.log("features.js written:", src.features.length, "features,", src.categories.length, "categories");
